<script setup lang="ts">
import { ChevronDown, FileText, Loader2 } from "lucide-vue-next";
import { Badge } from "~/components/ui/badge";
import { Button } from "~/components/ui/button";
import {
  formatDateTime,
  getLogLevelColor,
  syntaxHighlight,
  type WorkflowLogMessage,
} from "~/components/workflows/execution";

defineProps<{
  messages: WorkflowLogMessage[];
  loading: boolean;
  totalMessages: number;
}>();

const emit = defineEmits<{
  (e: "load-more"): void;
}>();
</script>

<template>
  <div>
    <!-- Messages Loading -->
    <div
      v-if="loading && messages.length === 0"
      class="flex items-center justify-center py-8"
    >
      <Loader2 class="h-6 w-6 animate-spin" />
    </div>

    <!-- Messages List -->
    <div v-else-if="messages.length > 0" class="space-y-2">
      <div
        v-for="message in messages"
        :key="`${message.step_id}-${message.log_time}`"
        class="rounded-lg border p-3 transition-colors hover:bg-muted/25 sm:p-4"
      >
        <div
          class="flex flex-col gap-2 sm:flex-row sm:items-start sm:justify-between sm:gap-4"
        >
          <div class="flex min-w-0 flex-1 items-start gap-2 sm:gap-3">
            <!-- Log Level Badge -->
            <Badge
              variant="outline"
              :class="getLogLevelColor(message.log_level)"
              class="shrink-0 font-mono text-xs"
            >
              {{ message.log_level }}
            </Badge>

            <!-- Message Content -->
            <div class="min-w-0 flex-1">
              <div
                class="mb-1 flex flex-wrap items-center gap-1 text-xs sm:gap-2 sm:text-sm"
              >
                <span class="font-medium text-foreground">
                  {{ message.step_name }}
                </span>
                <span class="hidden text-muted-foreground sm:inline">•</span>
                <span class="text-xs text-muted-foreground">
                  {{ formatDateTime(message.log_time) }}
                </span>
              </div>
              <p class="break-words text-xs text-foreground sm:text-sm">
                {{ message.message }}
              </p>

              <!-- Variables and Metadata (if present) -->
              <div
                v-if="
                  message.variables && Object.keys(message.variables).length > 0
                "
                class="mt-2"
              >
                <details class="text-xs">
                  <summary
                    class="cursor-pointer text-muted-foreground hover:text-foreground"
                  >
                    Variables
                  </summary>
                  <div
                    class="mt-1 max-h-24 overflow-auto whitespace-pre-wrap break-words rounded bg-muted p-2 font-mono"
                    v-html="
                      syntaxHighlight(JSON.stringify(message.variables, null, 2))
                    "
                  ></div>
                </details>
              </div>

              <div
                v-if="
                  message.metadata && Object.keys(message.metadata).length > 0
                "
                class="mt-2"
              >
                <details class="text-xs">
                  <summary
                    class="cursor-pointer text-muted-foreground hover:text-foreground"
                  >
                    Metadata
                  </summary>
                  <div
                    class="mt-1 max-h-24 overflow-auto whitespace-pre-wrap break-words rounded bg-muted p-2 font-mono"
                    v-html="
                      syntaxHighlight(JSON.stringify(message.metadata, null, 2))
                    "
                  ></div>
                </details>
              </div>
            </div>
          </div>
        </div>
      </div>

      <!-- Messages Pagination -->
      <div
        v-if="totalMessages > messages.length"
        class="flex justify-center pt-4"
      >
        <Button
          variant="outline"
          :disabled="loading"
          class="w-full text-xs sm:w-auto sm:text-sm"
          @click="emit('load-more')"
        >
          <ChevronDown class="mr-1 h-3 w-3 sm:mr-2 sm:h-4 sm:w-4" />
          Load More Messages ({{ totalMessages - messages.length }} remaining)
        </Button>
      </div>
    </div>

    <!-- No Messages -->
    <div v-else class="py-6 text-center text-muted-foreground sm:py-8">
      <FileText class="mx-auto mb-3 h-8 w-8 opacity-50 sm:mb-4 sm:h-12 sm:w-12" />
      <p class="text-sm sm:text-base">No log messages found</p>
      <p class="mt-2 px-2 text-xs sm:text-sm">
        Log messages are generated by
        <code class="rounded bg-muted px-1 text-xs">log()</code>,
        <code class="rounded bg-muted px-1 text-xs">log_debug()</code>,
        <code class="rounded bg-muted px-1 text-xs">log_warn()</code>, and
        <code class="rounded bg-muted px-1 text-xs">log_error()</code>
        functions in Lua scripts.
      </p>
    </div>
  </div>
</template>
